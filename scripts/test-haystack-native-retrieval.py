from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from rag3.retrieval import search

COLLECTION = "rag3_haystack_smoke"
QUERY = "Which embeddings are generated by one BGE-M3 encode call?"


def main() -> None:
    direct = search(
        QUERY,
        mode="hybrid",
        top_k=3,
        collection=COLLECTION,
    )
    if not direct["hits"]:
        raise SystemExit("Direct Haystack hybrid retrieval returned no hits")

    first = direct["hits"][0]
    if "dense embeddings" not in first["content"].lower():
        raise SystemExit("Unexpected top retrieval result")

    mcp_path = ROOT / "scripts" / "rag3-mcp-server.py"
    spec = importlib.util.spec_from_file_location("rag3_mcp_server_smoke", mcp_path)
    if spec is None or spec.loader is None:
        raise SystemExit("Could not load MCP server module")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    tool_fn = getattr(module, "search_rag3", None)
    if tool_fn is None:
        raise SystemExit("MCP search tool function missing")

    # MCP decorator may wrap the function. Validate that the module imports and the tool exists;
    # direct invocation is attempted only if the exported object remains callable.
    mcp_callable = callable(tool_fn)
    mcp_result = None
    if mcp_callable:
        try:
            mcp_result = tool_fn(QUERY, mode="hybrid", top_k=3)
        except TypeError:
            mcp_result = None

    result = {
        "direct_hit_count": len(direct["hits"]),
        "direct_top_chunk_id": first["chunk_id"],
        "direct_top_score": first["score"],
        "mcp_tool_present": True,
        "mcp_tool_callable": mcp_callable,
        "mcp_direct_call_hit_count": (
            len(mcp_result.get("hits", []))
            if isinstance(mcp_result, dict)
            else None
        ),
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
