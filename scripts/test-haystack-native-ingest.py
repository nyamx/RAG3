from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from rag3.haystack_native import ingest_source

COLLECTION = "rag3_haystack_smoke"


def main() -> None:
    fixture_dir = ROOT / "artifacts" / "haystack-native-smoke"
    fixture_dir.mkdir(parents=True, exist_ok=True)
    source = fixture_dir / "smoke.txt"
    source.write_text(
        "RAG3 Haystack native smoke test.\n\n"
        "The quick brown fox jumps over the lazy dog.\n"
        "Dense embeddings are generated by one BGE-M3 encode call.\n",
        encoding="utf-8",
    )

    first = ingest_source(source, collection=COLLECTION, recreate_index=True)
    second = ingest_source(source, collection=COLLECTION, recreate_index=False)

    result = {
        "first": first,
        "second": second,
        "idempotent_count": first["count_after"] == second["count_after"],
        "source_preserved": Path(first["managed_source"]).is_file(),
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))

    if not result["source_preserved"]:
        raise SystemExit("source preservation failed")
    if not result["idempotent_count"]:
        raise SystemExit("idempotent overwrite count failed")
    if not first["count_after"]:
        raise SystemExit("no documents written")


if __name__ == "__main__":
    main()
